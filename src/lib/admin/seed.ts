export const SEED_RFQS: RFQ[] = [];

const MIGRATION_FLAG = "edarcon_rfq_migrated";
const LEADS_KEY = "edarcon_leads";

export function migrateLegacyLeads(): void {
  if (typeof window === "undefined") return;
  try {
    if (localStorage.getItem(MIGRATION_FLAG) === "1") return;
    const raw = localStorage.getItem(LEADS_KEY);
    if (!raw) return;
    const parsed = JSON.parse(raw) as unknown;
    if (!Array.isArray(parsed)) return;
    const leads = parsed as Array<{
      name?: string;
      email?: string;
      phone?: string;
      service?: string;
      details?: string;
      locale?: string;
      createdAt?: string;
    }>;
    if (leads.length === 0) return;
    const existing = (seedData.rfqs as RFQ[]) ?? [];
    let index = existing.length;
    const next: RFQ[] = [...existing];
    for (const lead of leads) {
      index += 1;
      const status: RFQStatus = "new";
      const now = new Date().toISOString();
      next.push({
        id: crypto.randomUUID(),
        createdAt: lead.createdAt ?? now,
        updatedAt: now,
        referenceNo: `RFQ-${new Date().getFullYear()}-${String(index).padStart(4, "0")}`,
        name: lead.name ?? "",
        email: lead.email ?? "",
        phone: lead.phone ?? "",
        company: "",
        service: lead.service ?? "General Enquiry",
        source: "chatbot",
        language: (lead.locale === "ar" ? "ar" : "en") as "en" | "ar",
        message: { en: lead.details ?? "", ar: "" },
        status,
        assignedTo: undefined,
        followUpDate: undefined,
        timeline: [
          {
            id: crypto.randomUUID(),
            status,
            changedBy: "migration",
            changedAt: lead.createdAt ?? now,
            note: "Migrated from legacy chatbot lead",
          },
        ],
        notes: [],
      });
    }
    localStorage.setItem(`edarcon_db_rfqs`, JSON.stringify(next));
    localStorage.setItem(MIGRATION_FLAG, "1");
  } catch {
    // ignore migration errors
  }
}

