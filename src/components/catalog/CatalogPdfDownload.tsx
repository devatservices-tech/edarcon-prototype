"use client";

import { Button } from "@/components/ui/button";
import { Download } from "lucide-react";
import { jsPDF } from "jspdf";

interface CatalogPdfDownloadProps {
  name: string;
  categoryLabel: string;
  availabilityLabel: string;
  description: string;
  features: string[];
  applications: string[];
  specs: { label: string; value: string }[];
}

export function CatalogPdfDownload({
  name,
  categoryLabel,
  availabilityLabel,
  description,
  features,
  applications,
  specs,
}: CatalogPdfDownloadProps) {
  const downloadCatalogPdf = () => {
    const doc = new jsPDF();
    const pageWidth = doc.internal.pageSize.getWidth();
    const margin = 20;
    let y = 20;

    doc.setFont("helvetica", "bold");
    doc.setFontSize(20);
    doc.text(name, margin, y);
    y += 10;

    doc.setFont("helvetica", "normal");
    doc.setFontSize(11);
    doc.setTextColor(100, 100, 100);
    doc.text(`${categoryLabel}  |  ${availabilityLabel}`, margin, y);
    y += 10;

    doc.setTextColor(0, 0, 0);
    doc.setFontSize(13);
    doc.setFont("helvetica", "bold");
    doc.text("Description", margin, y);
    y += 7;
    doc.setFont("helvetica", "normal");
    doc.setFontSize(11);
    const descLines = doc.splitTextToSize(description, pageWidth - 2 * margin);
    doc.text(descLines, margin, y);
    y += descLines.length * 6 + 8;

    if (features.length > 0) {
      doc.setFont("helvetica", "bold");
      doc.setFontSize(13);
      doc.text("Features", margin, y);
      y += 7;
      doc.setFont("helvetica", "normal");
      doc.setFontSize(11);
      features.forEach((f) => {
        doc.text(`- ${f}`, margin, y);
        y += 6;
      });
      y += 4;
    }

    if (applications.length > 0) {
      doc.setFont("helvetica", "bold");
      doc.setFontSize(13);
      doc.text("Typical Applications", margin, y);
      y += 7;
      doc.setFont("helvetica", "normal");
      doc.setFontSize(11);
      applications.forEach((a) => {
        doc.text(`- ${a}`, margin, y);
        y += 6;
      });
      y += 4;
    }

    doc.setFont("helvetica", "bold");
    doc.setFontSize(13);
    doc.text("Specifications", margin, y);
    y += 7;
    doc.setFont("helvetica", "normal");
    doc.setFontSize(11);
    specs.forEach((spec) => {
      doc.text(`${spec.label}: ${spec.value}`, margin, y);
      y += 6;
    });
    y += 8;

    doc.setFont("helvetica", "italic");
    doc.setFontSize(9);
    doc.setTextColor(120, 120, 120);
    doc.text("Generated by Edarcon Contracting — Equipment Catalog", margin, y);

    doc.save(`${name.replace(/\s+/g, "-")}-catalog.pdf`);
  };

  return (
    <Button
      onClick={downloadCatalogPdf}
      variant="outline"
      size="sm"
      className="flex items-center justify-center gap-2 w-full px-6 py-3.5 rounded-xl border border-border text-sm font-medium text-foreground hover:bg-muted transition-colors"
    >
      <Download size={16} aria-hidden="true" />
      Download PDF
    </Button>
  );
}
